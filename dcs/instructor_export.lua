-- DCS-Instructor cockpit export. Loaded from Saved Games/DCS/Scripts/Export.lua by one marked line
-- (tools/install_export.py). Streams the player's aircraft state and cockpit argument values as JSON over
-- localhost UDP to the client. Read-only: it never sends commands to the aircraft.
-- Chains any LuaExport* functions defined before it (SRS defines some), so other exports keep working.

local INSTRUCTOR_DIR = assert(INSTRUCTOR_DIR, 'INSTRUCTOR_DIR must be set by the Export.lua line')
local HOST, PORT = '127.0.0.1', INSTRUCTOR_PORT or 47820
local INTERVAL = 0.2          -- seconds between updates (5 Hz)
local SNAPSHOT_EVERY = 5.0    -- seconds between full cockpit snapshots; changes only in between
local ARG_EPSILON = 0.001

package.path = package.path .. ';.\\LuaSocket\\?.lua'
package.cpath = package.cpath .. ';.\\LuaSocket\\?.dll'
local socket = require('socket')

local udp, aircraft, args, last_values, next_send, next_snapshot

local function log_info(text) if log then log.write('DCS_INSTRUCTOR', log.INFO, text) end end

local function json(value)
    local kind = type(value)
    if kind == 'number' then
        if value ~= value or value == math.huge or value == -math.huge then return 'null' end
        return string.format('%.4f', value):gsub('%.?0+$', '')
    end
    if kind == 'string' then return '"' .. value:gsub('[%c"\\]', function(c) return string.format('\\u%04x', c:byte()) end) .. '"' end
    if kind == 'boolean' then return tostring(value) end
    if kind == 'table' then
        local parts = {}
        if #value > 0 then
            for i = 1, #value do parts[i] = json(value[i]) end
            return '[' .. table.concat(parts, ',') .. ']'
        end
        for k, v in pairs(value) do parts[#parts + 1] = json(tostring(k)) .. ':' .. json(v) end
        return '{' .. table.concat(parts, ',') .. '}'
    end
    return 'null'
end

-- The argument list comes from the module folder (modules/<aircraft>/export_args.lua, generated by
-- tools/build_module.py). Unknown aircraft: flight data only.
local function load_args(name)
    local path = INSTRUCTOR_DIR .. 'modules\\' .. name .. '\\export_args.lua'
    local chunk = loadfile(path)
    if not chunk then log_info('no cockpit argument list for ' .. name); return {} end
    local ok, list = pcall(chunk)
    if not ok or type(list) ~= 'table' then log_info('bad argument list ' .. path); return {} end
    log_info(string.format('%s: %d cockpit arguments', name, #list))
    return list
end

local function flight_state(self)
    local state = {
        aircraft = self.Name,
        ias_ms = LoGetIndicatedAirSpeed(),
        tas_ms = LoGetTrueAirSpeed(),
        mach = LoGetMachNumber(),
        alt_msl_m = LoGetAltitudeAboveSeaLevel(),
        alt_agl_m = LoGetAltitudeAboveGroundLevel(),
        vvi_ms = LoGetVerticalVelocity(),
        aoa_deg = LoGetAngleOfAttack(),
        g = (LoGetAccelerationUnits() or {}).y,
        lat = self.LatLongAlt and self.LatLongAlt.Lat,
        lon = self.LatLongAlt and self.LatLongAlt.Long,
        heading_deg = self.Heading and math.deg(self.Heading),
        pitch_deg = self.Pitch and math.deg(self.Pitch),
        bank_deg = self.Bank and math.deg(self.Bank),
    }
    -- Magnetic heading: only for the local magnetic variation (true - magnetic), to give the wind as a tower does.
    local magnetic = LoGetMagneticYaw and LoGetMagneticYaw()
    if type(magnetic) == 'number' then state.mag_heading_deg = math.deg(magnetic) end
    local engine = LoGetEngineInfo()
    if engine and engine.RPM then state.rpm_left, state.rpm_right = engine.RPM.left, engine.RPM.right end
    return state
end

-- Radio state as SRS sees it. SRS's export (loaded before this file) computes the player's radios every frame with
-- its own exporter for the aircraft (Saved Games/DCS/Mods/Services/DCS-SRS/Scripts/DCS-SRS-Modules). We wrap that
-- function in memory to keep a copy of its result, which is passed back to SRS untouched; no SRS file is changed.
-- If SRS reloads its exporters, the wrapper is applied again.
-- SRS 2.4.1.0 keeps its table in a local ("local SR = {}"), so it is found as an upvalue of the export functions SRS
-- defines globally (LuaExportBeforeNextFrame uses SR); a global SR is used if a version has one.
local srs_radio, srs_wrappers = nil, {}
local upvalues_seen = 0   -- diagnostic for dcs.log: 0 means the debug library gives nothing here

local function srs_in(fn, depth, seen)
    if type(fn) ~= 'function' or depth > 3 or seen[fn] then return nil end
    seen[fn] = true
    for i = 1, 64 do
        local name, value = debug.getupvalue(fn, i)
        if name == nil then break end
        upvalues_seen = upvalues_seen + 1
        -- By its shape, not only its name: upvalue names are empty in code loaded without debug information.
        if type(value) == 'table' and type(value.exporters) == 'table' and type(value.exporter) == 'function' then
            return value
        end
        local found = srs_in(value, depth + 1, seen)   -- other tools may have wrapped SRS's functions
        if found then return found end
    end
    return nil
end

local function find_srs()
    if type(SR) == 'table' and type(SR.exporters) == 'table' then return SR end
    if type(debug) ~= 'table' or type(debug.getupvalue) ~= 'function' then return nil end
    local seen = {}
    for _, fn in ipairs({LuaExportBeforeNextFrame, LuaExportActivityNextEvent, LuaExportAfterNextFrame,
                         LuaExportStart, LuaExportStop}) do
        local found = srs_in(fn, 1, seen)
        if found then return found end
    end
    return nil
end

-- Looked up now, while the export functions are still SRS's (its Export.lua line runs before ours); again later if
-- SRS loads after us.
local srs = find_srs()
log_info(srs and 'SRS radio data found' or
         ('SRS radio data not found yet (debug library ' .. (type(debug) == 'table' and 'present' or 'missing') ..
          ', ' .. upvalues_seen .. ' upvalues seen)'))

local function watch_srs(name)
    srs = srs or find_srs()
    if not srs then return end
    local current = srs.exporters[name]
    if type(current) ~= 'function' or current == srs_wrappers[name] then return end
    local wrapper = function(data, sr)
        local result = current(data, sr)
        pcall(function()
            local radios = {}
            for i, radio in ipairs(result.radios or {}) do
                radios[i] = {name = radio.name, freq = radio.freq, modulation = radio.modulation,
                             secFreq = radio.secFreq}
            end
            srs_radio = {selected = result.selected, ptt = result.ptt, radios = radios}
        end)
        return result
    end
    srs.exporters[name] = wrapper
    srs_wrappers[name] = wrapper
    log_info('watching SRS radios of ' .. name)
end

-- Radio state from the cockpit itself, when SRS's own data is not reachable: the module lists its radios' DCS
-- devices (modules/<aircraft>/radios.lua); a radio that is off reports frequency 0, as in SRS.
local cockpit_radios = nil

local function load_radios(name)
    local chunk = loadfile(INSTRUCTOR_DIR .. 'modules\\' .. name .. '\\radios.lua')
    if not chunk then return nil end
    local ok, list = pcall(chunk)
    if ok and type(list) == 'table' and type(list.radios) == 'table' then return list end
    log_info('bad radio list for ' .. name)
    return nil
end

-- Optional per module (modules/<aircraft>/radios.lua): modulation fixed (0 AM, 1 FM) or by a cockpit argument
-- (modulation_arg: FM above 0.5); the selected radio by a selector argument (selector = {arg, step, positions =
-- {[position] = radio}}, any other position = none), an intercom switch (intercom_arg) and PTT buttons (ptt_args),
-- as SRS's own exporter for that aircraft reads them. Without them: the device's modulation, radio "selected".
local function argument(arg)
    local ok, value = pcall(function() return GetDevice(0):get_argument_value(arg) end)
    return ok and type(value) == 'number' and value or 0
end

local function read_cockpit_radios()
    if not cockpit_radios then return nil end
    local radios = {{name = 'intercom', freq = 100, modulation = 2}}
    for i, radio in ipairs(cockpit_radios.radios) do
        local entry = {name = radio.name, freq = 0, modulation = radio.modulation or 0}
        local device = GetDevice(radio.device)
        if device and type(device) ~= 'number' then
            pcall(function()
                if device:is_on() then entry.freq = device:get_frequency() end
            end)
            if radio.modulation == nil and radio.modulation_arg == nil then
                pcall(function() entry.modulation = device:get_modulation() end)
            end
        end
        if radio.modulation_arg then entry.modulation = argument(radio.modulation_arg) > 0.5 and 1 or 0 end
        radios[i + 1] = entry
    end
    local selected = cockpit_radios.selected or 1
    local selector = cockpit_radios.selector
    if selector then
        local position = math.floor(argument(selector.arg) / selector.step + 0.5)
        selected = selector.positions[position] or -1
    end
    if cockpit_radios.intercom_arg and argument(cockpit_radios.intercom_arg) > 0.5 then selected = 0 end
    local ptt = false
    for _, arg in ipairs(cockpit_radios.ptt_args or {}) do ptt = ptt or argument(arg) >= 0.5 end
    return {selected = selected, radios = radios, ptt = ptt, source = 'cockpit'}
end

-- Any aircraft, mods too, without a modules/<aircraft>/radios.lua (live 2026-11-02: an F-16 on Syria had no radio
-- data, so every press went to the instructor on 251 and the pilot, on Akrotiri's tower frequency, heard nothing):
-- on entering, the cockpit devices that answer get_frequency() are the radios (as SRS reads most aircraft). Which
-- one is selected is not known: "selected" is left out; the program uses radio 1, or radio 2 for the pilot's second
-- push-to-talk button (shared/radio.transmit_radio).
local DEVICE_SCAN_MAX = 100
local scanned_radios = nil

local function comm_frequency(freq)   -- communication bands only: not the ILS/VOR (108-118 MHz) or ADF receivers
    return type(freq) == 'number' and freq >= 30e6 and freq <= 400e6 and not (freq >= 108e6 and freq < 118e6)
end

local function scan_radios()
    local found = {}
    for id = 1, DEVICE_SCAN_MAX do
        local ok, device = pcall(GetDevice, id)
        if ok and device and type(device) ~= 'number' then
            -- A radio: answers, and is on a communication band (or 0: switched off). Navigation receivers (ILS, VOR,
            -- ADF) are left out, so radio 1 and 2 are the aircraft's communication radios in device order.
            local answers, freq = pcall(function() return device:get_frequency() end)
            if answers and (freq == 0 or comm_frequency(freq)) then found[#found + 1] = id end
        end
    end
    return found
end

local function read_scanned_radios()
    if not scanned_radios or #scanned_radios == 0 then return nil end
    local radios = {{name = 'intercom', freq = 100, modulation = 2}}
    for _, id in ipairs(scanned_radios) do
        local entry = {name = 'radio ' .. id, freq = 0, modulation = 0}
        pcall(function()
            local device = GetDevice(id)
            local on = true
            pcall(function() on = device:is_on() end)
            local freq = device:get_frequency()
            if on and comm_frequency(freq) then entry.freq = freq end
            local modulation = device:get_modulation()
            if modulation == 0 or modulation == 1 then entry.modulation = modulation end
        end)
        radios[#radios + 1] = entry
    end
    return {radios = radios, ptt = false, source = 'devices'}
end

local function send(message)
    if udp then udp:sendto(json(message), HOST, PORT) end
end

local function tick()
    local now = LoGetModelTime()
    if now < next_send then return end
    next_send = now + INTERVAL

    local self = LoGetSelfData()
    if not self then
        if aircraft then send({type = 'left_aircraft', time = now}); aircraft = nil end
        return
    end
    if self.Name ~= aircraft then
        aircraft = self.Name
        args = load_args(aircraft)
        last_values = {}
        srs_radio = nil
        cockpit_radios = load_radios(aircraft)
        scanned_radios = nil
        if not srs and not cockpit_radios then
            scanned_radios = scan_radios()
            log_info(aircraft .. ': radio devices found ' .. table.concat(scanned_radios, ', '))
        end
        log_info(aircraft .. ': radios from ' .. (srs and 'SRS' or (cockpit_radios and 'cockpit devices' or
                 (#scanned_radios > 0 and 'scanned devices' or 'nowhere'))))
        next_snapshot = now
        send({type = 'aircraft', time = now, aircraft = aircraft, arg_count = #args})
    end

    local device = GetDevice(0)
    local snapshot = now >= next_snapshot
    local changed = {}
    if device then
        for _, arg in ipairs(args) do
            local value = device:get_argument_value(arg)
            local last = last_values[arg]
            if snapshot or last == nil or math.abs(value - last) > ARG_EPSILON then
                changed[tostring(arg)] = value
                last_values[arg] = value
            end
        end
    end
    if snapshot then next_snapshot = now + SNAPSHOT_EVERY end
    watch_srs(aircraft)
    send({type = snapshot and 'snapshot' or 'update', time = now, flight = flight_state(self), args = changed,
          radio = srs_radio or read_cockpit_radios() or read_scanned_radios()})
end

-- Chain with whatever was defined before (SRS, other tools).
local previous_start, previous_after, previous_stop = LuaExportStart, LuaExportAfterNextFrame, LuaExportStop

LuaExportStart = function()
    if previous_start then pcall(previous_start) end
    udp = socket.udp()
    udp:settimeout(0)
    aircraft, args, last_values, next_send, next_snapshot = nil, {}, {}, 0, 0
    log_info('started, sending to ' .. HOST .. ':' .. PORT)
end

LuaExportAfterNextFrame = function()
    if previous_after then pcall(previous_after) end
    local ok, err = pcall(tick)
    if not ok then log_info('tick error: ' .. tostring(err)) end
end

LuaExportStop = function()
    if previous_stop then pcall(previous_stop) end
    if udp then send({type = 'stop'}); udp:close(); udp = nil end
end
