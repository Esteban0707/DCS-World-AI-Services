"""Generate an aircraft module's cockpit data from the DCS install, using DCS's own Lua interpreter.

Usage (Windows, where DCS lives):
    python tools/build_module.py --dcs "E:/DCS World" --source "F-5E 2024" --module F-5E-3

Writes modules/<module>/controls.json (clickable cockpit controls) and modules/<module>/autostart.json
(DCS's own autostart sequence, a reference for the cold-start procedure). Never modifies the DCS install.
"""
import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DUMPER = ROOT / 'tools' / 'dcs' / 'dump_cockpit.lua'


def dump(luae: Path, scripts_dir: Path, what: str):
    result = subprocess.run([str(luae), str(DUMPER), scripts_dir.as_posix() + '/', what],
                            capture_output=True, timeout=60)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.decode('utf-8', 'replace').strip())
    return json.loads(result.stdout.decode('utf-8'))


def link_steps_to_controls(steps: list, controls: list, command_tables: dict) -> None:
    """Command ids repeat across devices, so a step is identified by (device, command id). Adds the command name,
    and the clickable control plus the cockpit argument(s) that show the result when a control sends that command.
    Steps without a clickable control are named through the command table their device uses in the controls."""
    by_command = {}
    tables_by_device = {}
    for control in controls:
        for action in control['actions']:
            by_command.setdefault((control['device'], action['id']), (action.get('name'), control))
            if action.get('name'):
                tables_by_device.setdefault(control['device'], set()).add(action['name'].split('.')[0])
    for step in steps:
        match = by_command.get((step.get('device'), step.get('action')))
        if match:
            name, control = match
            step.update(action_name=name, control=control['id'], hint=control['hint'],
                        arg=sorted(set(control['arg'])))
        elif 'action' in step:
            names = [f'{table}.{key}' for table in sorted(tables_by_device.get(step.get('device'), ()))
                     for key, value in command_tables.get(table, {}).items() if value == step['action']]
            if names:
                step['action_name'] = '|'.join(names)


def write_export_args(module_dir: Path) -> int:
    """Write export_args.lua: every cockpit argument the instructor may need for this aircraft, i.e. the clickable
    controls plus the arguments the training lessons check (gauges such as trim indicators are not clickable).
    The cockpit export (dcs/instructor_export.lua) reads exactly these. Returns how many."""
    controls = json.loads((module_dir / 'controls.json').read_text(encoding='utf-8'))['controls']
    args = {arg for control in controls for arg in control['arg'] if isinstance(arg, int)}
    for lesson in (module_dir / 'training').glob('*.json'):
        for rule in json.loads(lesson.read_text(encoding='utf-8'))['rules']:
            args.update(c['arg'] for c in rule['conditions'] if c['predicate'] == 'c_argument_in_range')
    (module_dir / 'export_args.lua').write_text(
        '-- Generated by tools/build_module.py: cockpit arguments read by dcs/instructor_export.lua.\n'
        f'return {{{", ".join(map(str, sorted(args)))}}}\n', encoding='utf-8')
    return len(args)


def missing(module_dir: Path) -> list[str]:
    """The module's cockpit files built from DCS that are absent or unreadable (a write cut short): controls.json,
    autostart.json, export_args.lua (here) and positions.json (tools/build_positions.py). For tools/setup.py."""
    found = []
    for name, key in (('controls.json', 'controls'), ('autostart.json', 'steps'), ('positions.json', 'args')):
        try:
            if json.loads((module_dir / name).read_text(encoding='utf-8'))[key]:
                continue
        except (OSError, ValueError, KeyError, TypeError):
            pass
        found.append(name)
    try:
        if not (module_dir / 'export_args.lua').read_text(encoding='utf-8').rstrip().endswith('}'):
            found.append('export_args.lua')
    except OSError:
        found.append('export_args.lua')
    return found


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--dcs', required=True, help='DCS World install folder')
    parser.add_argument('--source', required=True, help='folder name under Mods/aircraft')
    parser.add_argument('--module', required=True, help='module folder name under modules/')
    args = parser.parse_args()

    dcs = Path(args.dcs)
    scripts_dir = dcs / 'Mods' / 'aircraft' / args.source / 'Cockpit' / 'Scripts'
    luae = dcs / 'bin' / 'luae.exe'
    source = {'dcs_folder': f'Mods/aircraft/{args.source}', 'generated_by': 'tools/build_module.py'}

    controls = dump(luae, scripts_dir, 'controls')
    autostart = dump(luae, scripts_dir, 'macro')
    link_steps_to_controls(autostart, controls, dump(luae, scripts_dir, 'commands'))

    out_dir = ROOT / 'modules' / args.module
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / 'controls.json').write_text(
        json.dumps({'source': source, 'controls': controls}, indent=1, ensure_ascii=False), encoding='utf-8')
    (out_dir / 'autostart.json').write_text(
        json.dumps({'source': source, 'steps': autostart}, indent=1, ensure_ascii=False), encoding='utf-8')
    export_args = write_export_args(out_dir)
    print(f'{out_dir}: {len(controls)} controls, {len(autostart)} autostart steps, {export_args} export args')


if __name__ == '__main__':
    main()
