"""Radar cross section of every aircraft type, from DCS's own aircraft definitions (read-only).

Usage: python tools/build_rcs.py [dcs_install]   (default: settings "dcs.install")
Each aircraft definition file in CoreMods/aircraft and Mods/aircraft gives its type name (Name = 'F-5E-3') and its
RCS in square metres (RCS = 4, "Radar Cross Section m2"). Writes dcs/aircraft_rcs.lua, a Lua table the GUI hook
sends to the mission scripting environment with the radar script (dcs/instructor_radar.lua scales each radar's
detection distance by it). Files with several aircraft are split at each Name.
Only the modules' plain-text definitions are covered: AI-only aircraft (Su-25T, C-130...) live in DCS's compiled
database, so the radar script asks DCS at run time first (Unit:getDesc().RCS) and uses this table as a fallback.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'dcs' / 'aircraft_rcs.lua'
FOLDERS = ('CoreMods/aircraft', 'Mods/aircraft')
NAME = re.compile(r'''(?<![A-Za-z_])Name\s*=\s*['"]([^'"]+)['"]''')   # not DisplayName / shortName
RCS = re.compile(r'^\s*RCS\s*=\s*([0-9]*\.?[0-9]+)', re.M)
RUNWAY_CATEGORIES = ('AircraftCarrier', 'HelicopterCarrier')   # DCS's takeoff/landing categories, not aircraft
LIST_ELEMENT = re.compile(r'^\s*\[\d+\]\s*=\s*\{?\s*$')
SENSOR_BLOCK = re.compile(r'surface_search|Sensors\.lua$', re.I)   # RCS there is a radar's ground reference, not ours


def inline_entry(text: str, name: re.Match) -> bool:
    """A Name inside a one-line table or a numbered list element, e.g. the runway categories
    [1] = { Name = "AircraftCarrier" }, is not an aircraft; the MiG-21's one-line rewrite_settings
    {Name = 'MiG-21Bis', DisplayName = ...} is."""
    line_start = text.rfind('\n', 0, name.start()) + 1
    line_end = text.find('\n', name.end())
    line = text[line_start:line_end if line_end >= 0 else len(text)]
    if '{' in text[line_start:name.start()] and 'DisplayName' not in line:
        return True
    before = text[max(0, line_start - 200):line_start].rstrip().splitlines()[-2:]
    return any(LIST_ELEMENT.match(previous) for previous in before)


def scan(install: Path) -> dict[str, float]:
    table = {}
    for folder in FOLDERS:
        for path in sorted((install / folder).rglob('*.lua')):
            if SENSOR_BLOCK.search(path.name):
                continue
            try:
                text = path.read_text(encoding='utf-8', errors='replace')
            except OSError:
                continue
            names = [n for n in NAME.finditer(text) if not inline_entry(text, n)]
            # The RCS that follows each Name, before the next Name, belongs to that aircraft.
            for i, name in enumerate(names):
                end = names[i + 1].start() if i + 1 < len(names) else len(text)
                rcs = RCS.search(text, name.end(), end)
                if rcs and name.group(1) not in table and not name.group(1).startswith(RUNWAY_CATEGORIES):
                    table[name.group(1)] = float(rcs.group(1))
    return table


def write(table: dict[str, float], install: Path) -> None:
    lines = ['-- Generated by tools/build_rcs.py from the DCS install (aircraft definitions: RCS in m2). Do not edit.',
             f'-- Source: {install.as_posix()}, {len(table)} aircraft types.',
             'DCSInstructorRadar_RCS = {']
    lines += [f'    [{json.dumps(name)}] = {rcs:g},' for name, rcs in sorted(table.items())]
    lines.append('}')
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def built(path: Path = OUTPUT) -> bool:
    """The table is there and whole (a cut write ends before the closing brace): tools/setup.py."""
    try:
        text = path.read_text(encoding='utf-8')
    except OSError:
        return False
    return 'DCSInstructorRadar_RCS = {' in text and text.rstrip().endswith('}')


def main() -> None:
    settings = json.loads((ROOT / 'settings.json').read_text(encoding='utf-8'))
    install = Path(sys.argv[1] if len(sys.argv) > 1 else settings['dcs']['install'])
    table = scan(install)
    write(table, install)
    print(f'{len(table)} aircraft types -> {OUTPUT}')
    for name in ('F-5E-3', 'C-130', 'Su-25T', 'A-10C_2', 'F-16C_50', 'FA-18C_hornet', 'MiG-21Bis', 'UH-1H'):
        print(f'  {name}: {table.get(name, "not found")}')


if __name__ == '__main__':
    main()
